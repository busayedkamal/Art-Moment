const DYNAMIC_PATTERNS = [
  [/^يعرض\s+(\d+)\s+منتج\s+من\s+أصل\s+(\d+)$/u, (_, shown, total) => `Showing ${shown} of ${total} products`],
  [/^تصفح المتجر\s*\((\d+)\)$/u, (_, total) => `Browse store (${total})`],
  [/^المتوفر\s*:\s*(\d+)$/u, (_, count) => `${count} available`],
  [/^الكمية\s*:\s*(\d+)$/u, (_, count) => `Quantity: ${count}`],
  [/^عدد الطلبات\s*:\s*(\d+)$/u, (_, count) => `Orders: ${count}`],
  [/^طلب رقم\s*#?(.+)$/u, (_, id) => `Order #${id}`],
  [/^لديك\s+([\d,]+)\s+نقطة/u, (_, points) => `You have ${points} points`],
  [/^المتبقي\s+(.+)$/u, (_, value) => `Remaining ${value}`],
  [/^جميع الحقوق محفوظة لمتجر لحظة فن © (\d{4})$/u, (_, year) => `All rights reserved to Art Moment © ${year}`],
];

export function translateUiText(value, language = 'ar') {
  if (language !== 'en' || typeof value !== 'string') return value;

  const match = value.match(/^(\s*)(.*?)(\s*)$/s);
  const leading = match?.[1] || '';
  const text = match?.[2] || value;
  const trailing = match?.[3] || '';
  if (!text || !/\p{Script=Arabic}/u.test(text)) return value;

  const exact = UI_TRANSLATIONS[text];
  if (exact) return `${leading}${exact}${trailing}`;

  for (const [pattern, replacement] of DYNAMIC_PATTERNS) {
    if (pattern.test(text)) {
      pattern.lastIndex = 0;
      return `${leading}${text.replace(pattern, replacement)}${trailing}`;
    }
  }

  return value;
}
